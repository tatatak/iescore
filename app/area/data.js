export function getAreaBySlug(slug) {
  return areas.find(a => a.slug === slug) ?? null;
}

export function getNearbyAreas(area, count = 4) {
  return areas
    .filter(a => a.slug !== area.slug)
    .map(a => ({
      ...a,
      dist: Math.hypot(a.lat - area.lat, a.lng - area.lng),
    }))
    .sort((a, b) => a.dist - b.dist)
    .slice(0, count);
}
